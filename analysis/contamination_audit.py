"""
Pretraining-contamination sanity check for the Cassazione corpus.

The corpus is filtered to 2025–2026 publications, so most evaluated models
have pretraining cutoffs that pre-date many of the cases; models released in
2026 may have seen the earlier ones (see analysis/release_date_split.py).

This script computes two cheap signals per (case, model) pair:

  1. **Verbatim overlap.** Take all word-level n-grams of length N (default 12)
     from the published *Considerato in diritto*, and from the model's
     generated reasoning trace. Compute Jaccard overlap of the two n-gram sets.
     High overlap on a case the model couldn't possibly have generated by
     reasoning alone is the canonical contamination signal.

  2. **Date stratification.** Bucket cases by publication year-month parsed
     from the filename pattern `…@a<YYYY>@n…` and report mean overlap per
     bucket. A model that systematically scores higher on pre-cutoff cases
     than post-cutoff cases is a red flag.

Output: results/_contamination_audit.json with the full per-(model, case) grid
plus per-model summary statistics.

This is the lightweight version. For a full audit, follow up with
membership-inference frameworks (survey: arXiv:2404.00699; STAMP:
arXiv:2504.13416).
"""
from __future__ import annotations

import argparse
import json
import re
from collections import defaultdict
from pathlib import Path
from statistics import mean, stdev

ROOT          = Path(__file__).resolve().parent.parent
SENTENZE_DIR  = ROOT / "sentenze_md_filtered"
RESULTS_ROOT  = ROOT / "results"
OUT           = RESULTS_ROOT / "_contamination_audit.json"

FILENAME_YM_RE = re.compile(r"@a(\d{4})@n(\d+)")
PQM_RE         = re.compile(r"\n\s*P\.\s*Q\.\s*M\.", re.IGNORECASE)
CONSIDERATO_RE = re.compile(r"\nCONSIDERATO IN DIRITTO", re.IGNORECASE)

WORD_RE = re.compile(r"\w+", re.UNICODE)


def tokenize(text: str) -> list[str]:
    return [t.lower() for t in WORD_RE.findall(text)]


def ngrams(tokens: list[str], n: int) -> set[tuple]:
    if len(tokens) < n:
        return set()
    return {tuple(tokens[i:i + n]) for i in range(len(tokens) - n + 1)}


def jaccard(a: set, b: set) -> float:
    if not a and not b:
        return 0.0
    inter = len(a & b)
    union = len(a | b)
    return inter / union if union else 0.0


def parse_year(filename: str) -> int | None:
    m = FILENAME_YM_RE.search(filename)
    if not m:
        return None
    return int(m.group(1))


def extract_considerato(filename: str) -> str:
    p = SENTENZE_DIR / filename
    if not p.exists():
        return ""
    from pipeline.case_sections import split_case

    _parsed, _rule, considerato = split_case(p.read_text(encoding="utf-8"))
    return considerato


def audit_model(label: str, model_dir: Path, ngram_n: int) -> list[dict]:
    inf_file = model_dir / "inference_results.jsonl"
    if not inf_file.exists():
        return []
    rows: list[dict] = []
    with open(inf_file) as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            try:
                rec = json.loads(line)
            except json.JSONDecodeError:
                continue
            filename = rec.get("filename")
            trace    = rec.get("judge_reasoning_trace", "")
            if not filename or not trace:
                continue
            considerato = extract_considerato(filename)
            if not considerato:
                continue
            cons_grams  = ngrams(tokenize(considerato), ngram_n)
            trace_grams = ngrams(tokenize(trace), ngram_n)
            overlap     = jaccard(cons_grams, trace_grams)
            verbatim_hits = len(cons_grams & trace_grams)
            rows.append({
                "filename":      filename,
                "year":          parse_year(filename),
                "considerato_ngrams": len(cons_grams),
                "trace_ngrams":  len(trace_grams),
                "verbatim_hits": verbatim_hits,
                "jaccard":       round(overlap, 5),
            })
    return rows


def summarise(label: str, rows: list[dict]) -> dict:
    if not rows:
        return {"n": 0}
    jaccards = [r["jaccard"] for r in rows]
    hits     = [r["verbatim_hits"] for r in rows]
    by_year: dict[int, list[float]] = defaultdict(list)
    for r in rows:
        if r["year"] is not None:
            by_year[r["year"]].append(r["jaccard"])
    summary = {
        "n":               len(rows),
        "jaccard_mean":    round(mean(jaccards), 5),
        "jaccard_stdev":   round(stdev(jaccards), 5) if len(jaccards) > 1 else 0.0,
        "jaccard_max":     round(max(jaccards), 5),
        "verbatim_hits_mean": round(mean(hits), 3),
        "verbatim_hits_max":  max(hits),
        "by_year": {
            str(y): {
                "n":            len(vs),
                "jaccard_mean": round(mean(vs), 5),
            }
            for y, vs in sorted(by_year.items())
        },
    }
    suspicious = [r for r in rows if r["jaccard"] >= 0.05 or r["verbatim_hits"] >= 5]
    summary["suspicious_cases"] = [s["filename"] for s in sorted(suspicious, key=lambda r: -r["jaccard"])[:20]]
    summary["n_suspicious"] = len(suspicious)
    return summary


def main() -> None:
    parser = argparse.ArgumentParser(description="Pretraining-contamination sanity check (n-gram overlap)")
    parser.add_argument("--ngram", type=int, default=12, help="Word n-gram size (default: 12)")
    parser.add_argument("--results-root", type=Path, default=RESULTS_ROOT)
    parser.add_argument("--out", type=Path, default=OUT)
    parser.add_argument("--models", nargs="*", default=None,
                        help="Limit to these model labels (default: every directory under results/ with inference_results.jsonl)")
    args = parser.parse_args()

    if args.models:
        candidates = [args.results_root / m for m in args.models]
    else:
        candidates = [p for p in sorted(args.results_root.iterdir()) if p.is_dir()]

    per_model: dict[str, dict] = {}
    for model_dir in candidates:
        if not (model_dir / "inference_results.jsonl").exists():
            continue
        label = model_dir.name
        print(f"Auditing {label} (n-gram={args.ngram})…")
        rows = audit_model(label, model_dir, args.ngram)
        summary = summarise(label, rows)
        per_model[label] = {"summary": summary, "rows": rows}
        print(f"  → {summary['n']} cases, mean Jaccard={summary['jaccard_mean']}, "
              f"max={summary['jaccard_max']}, suspicious={summary['n_suspicious']}")

    args.out.parent.mkdir(parents=True, exist_ok=True)
    with open(args.out, "w") as fh:
        json.dump({"ngram": args.ngram, "per_model": per_model}, fh, indent=2)
    print(f"\nWrote {args.out}")


if __name__ == "__main__":
    main()
